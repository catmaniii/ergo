/** 第 p 百分位（最近名次法：从小到大排，取第 ⌈p·n⌉ 个）；空的是 NaN */
export function percentile(values: readonly number[], p: number): number {
  if (values.length === 0) return Number.NaN;
  const sorted = values.toSorted((a, b) => a - b);
  const rank = Math.min(sorted.length, Math.max(1, Math.ceil(p * sorted.length)));
  return sorted[rank - 1]!;
}

/** 背景向量：按向量函数（实例）和模型名缓存 */
const cache = new WeakMap<Embedder, Map<string, Promise<Float32Array[]>>>();

/** 背景语料的向量（文档角色）；同一个向量函数、同一个模型名只算一次，换了模型名重算 */
export function backgroundVectors(embedder: Embedder): Promise<Float32Array[]> {
  let byModel = cache.get(embedder);
  if (!byModel) {
    byModel = new Map();
    cache.set(embedder, byModel);
  }
  let vectors = byModel.get(embedder.model);
  if (!vectors) {
    vectors = embedder.embedDocuments(BACKGROUND_SENTENCES);
    byModel.set(embedder.model, vectors);
    // 算失败了不留在缓存里，下次重算
    vectors.catch(() => byModel!.delete(embedder.model));
  }
  return vectors;
}

/**
 * 这个问题的向量门槛：问题（查询角色）和背景语料每一句的余弦，取第 p 百分位。
 * 没有向量函数、模型不在时是 null（向量那一路不算命中）。
 */
export async function backgroundThreshold(embedder: Embedder | undefined, question: string, p: number = BACKGROUND_PERCENTILE): Promise<number | null> {
  if (!embedder || !embedder.available()) return null;
  const [q] = await embedder.embedQueries([question]);
  if (!q) return null;
  const docs = await backgroundVectors(embedder);
  return percentile(docs.map((d) => cosine(q, d)), p);
}
